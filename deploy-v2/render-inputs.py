#!/usr/bin/env python3
"""render-inputs.py — validate deploy-v2/inputs.yaml and render the estate files.

Usage:
  python3 deploy-v2/render-inputs.py deploy-v2/inputs.yaml --check
  python3 deploy-v2/render-inputs.py deploy-v2/inputs.yaml --render

--check  validates against inputs.schema.json, verifies every referenced
         key/cert file exists, and asserts no secret-looking values are
         embedded in the yaml (de-identification rule).
--render additionally writes deploy-v2/m0/hosts.env (the install scripts'
         single source of truth for VM names/IPs/VMIDs) and prints the
         per-stage staging plan.

Exit 0 = clean; exit 1 = any validation failure (lists every failure).
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
SCHEMA = HERE / "inputs.schema.json"

try:
    import yaml  # PyYAML
except ImportError:
    sys.exit("PyYAML required: pip install pyyaml")

# Secret-shaped values that must NEVER appear as literals in inputs.yaml
# (de-identification rule: secrets live in files, referenced by path).
SECRET_PATTERNS = [
    re.compile(r"(ghp|github_pat|sk-|rk-|shpat_)"),
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    re.compile(r"Bearer\s+[A-Za-z0-9._-]{20,}"),
]
KEYISH_FIELDS = re.compile(r"(key_path|token|secret|password)", re.I)


def load(inputs_path: pathlib.Path):
    return yaml.safe_load(inputs_path.read_text()), inputs_path


def validate(doc) -> list[str]:
    errs = []
    schema = json.loads(SCHEMA.read_text())
    try:
        import jsonschema
        validator = jsonschema.Draft202012Validator(schema)
        for e in sorted(validator.iter_errors(doc), key=lambda e: list(e.absolute_path)):
            loc = ".".join(str(p) for p in e.absolute_path) or "<root>"
            errs.append(f"schema: {loc}: {e.message}")
    except ImportError:
        errs.append("schema: python jsonschema module not installed — structural validation skipped "
                    "(pip install jsonschema); continuing with semantic checks only")

    # Fallback semantic checks (schema module missing)
    roles = [m.get("role") for m in doc.get("machines", [])]
    if sorted(roles) != ["execution", "front_of_house", "memory", "registry"]:
        errs.append(f"semantic: machines roles = {roles}, expected all four exactly once")

    # Semantic checks that always run
    machines = doc.get("machines", [])
    ips = [m.get("ip") for m in machines]
    if len(set(ips)) != len(ips):
        errs.append(f"semantic: duplicate machine IPs: {ips}")
    names = [m.get("name") for m in machines]
    if len(set(names)) != len(names):
        errs.append(f"semantic: duplicate machine names: {names}")
    nr = doc.get("estate", {}).get("name_resolution")
    if nr not in ("pve_dns", "hosts_file"):
        errs.append(f"semantic: estate.name_resolution must be pve_dns|hosts_file, got {nr!r}")

    # De-identification: no secret-shaped literals anywhere in the file
    text = json.dumps(doc)
    for pat in SECRET_PATTERNS:
        if pat.search(text):
            errs.append("de-identification: secret-shaped value found in inputs.yaml — "
                        "secrets are referenced BY PATH only; move the value into the file it points to")
    for k, v in _walk(doc):
        if KEYISH_FIELDS.search(str(k)) and isinstance(v, str) and "path" not in k.lower() and len(v) > 40:
            errs.append(f"de-identification: field '{k}' holds a long literal value — "
                        "path-referencing fields must end in _path")
    return errs


def _walk(doc, prefix=""):
    if isinstance(doc, dict):
        for k, v in doc.items():
            yield k, v
            yield from _walk(v, f"{prefix}.{k}")
    elif isinstance(doc, list):
        for item in doc:
            yield from _walk(item, prefix)


def check_files(doc) -> list[str]:
    errs = []
    import os
    refs = [
        ("ssh.key_path", doc.get("ssh", {}).get("key_path")),
        ("github.app_key_path", doc.get("github", {}).get("app_key_path")),
        ("model.provider_key_path", doc.get("model", {}).get("provider_key_path")),
    ]
    emb = doc.get("embedding") or {}
    if emb.get("enabled") and emb.get("provider_key_path"):
        refs.append(("embedding.provider_key_path", emb["provider_key_path"]))
    for name, path in refs:
        if path and not os.path.exists(os.path.expanduser(str(path))):
            errs.append(f"file: {name} -> {path}: file does not exist")
    return errs


def render_hosts_env(doc) -> str:
    lines = [
        "# hosts.env — GENERATED by render-inputs.py from inputs.yaml. Do not hand-edit;",
        "# edit inputs.yaml and re-render. Gitignored; the single source of truth",
        "# for VM names/IPs/VMIDs. Every script auto-loads it.",
        f"# estate: {doc['estate']['name']}  (name resolution: {doc['estate']['name_resolution']})",
        "",
    ]
    role_env = {"front_of_house": "VM_XA", "execution": "VM_XB",
                "memory": "VM_HINDSIGHT", "registry": "VM_REGISTRY"}
    for m in doc["machines"]:
        var = role_env[m["role"]]
        lines.append(f"# {m['role']}")
        lines.append(f"{var}={m['ip']}")
        lines.append(f"{var}_NAME={m['name']}")
        lines.append(f"{var}_VMID={m['vmid']}")
        lines.append("")
    # Container engine: podman = ROOTLESS Podman on the EXECUTION VM only;
    # every other VM is Docker (see decision-log.md). The install scripts
    # read ENGINE from hosts.env and branch on it for vm-xb commands.
    lines.append(f"ENGINE={doc['config']['engine']}")
    lines.append("")
    lines.append("# Ports (host-published)")
    for name, val in doc["ports"].items():
        lines.append(f"PORT_{name.upper()}={val}")
    lines.append("")
    c = doc["config"]
    lines += [
        f"EA_TTL_DEFAULT={c['ttl_default']}",
        f"MAX_PARALLEL_AGENTS={c['max_parallel_agents']}",
        f"REGISTRY_GC_KEEP_LAST={c['registry_gc_keep_last']}",
        f"REGISTRY_DISK_ALERT_PCT={c['registry_disk_alert_pct']}",
        f"ISOLATION_TIER={c['isolation_tier']}",
        "",
    ]
    g = doc["github"]
    lines += [f"GITHUB_ORG={g['org']}", f"GITHUB_APP_ID={g['app_id']}",
              f"ROSTER_REPO={g['repos']['roster']}", f"WIKI_REPO={g['repos']['wiki']}",
              f"DEMO_REPO={g['repos']['demo']}", f"MODEL_PROVIDER={doc['model']['provider']}",
              f"MODEL_DEFAULT={doc['model']['default_model']}"]
    return "\n".join(lines) + "\n"


def staging_plan(doc) -> list[str]:
    g, m = doc["github"], doc["model"]
    # engine choice (config.engine): podman = rootless Podman on the EXECUTION
    # VM only; every other VM stays Docker (see decision-log.md).
    engine = doc["config"]["engine"]
    eng = {"front_of_house": "docker", "execution": engine,
           "memory": "docker", "registry": "docker"}
    lines = [
        "STAGING PLAN (runbook stage order; secrets staged 0600, gitignored):",
        f"  S0   hosts.env written — {g['org']} estate, 4 machines",
        "  S0   container engine per VM: "
        + ", ".join(f"{mm['name']}={eng[mm['role']]}" for mm in doc["machines"])
        + ("  (rootless podman on the execution VM only)" if engine == "podman" else ""),
        f"  S1   registry basic-auth + CA minted on the registry VM -> deploy-v2/.env.registry",
        f"  S3   broker password minted -> deploy-v2/m0 (rabbitmq compose env)",
        f"  S6   model key {m['provider_key_path']} -> llm-proxy (executor class) + VM-Xa cos.env (CoS class);",
        "       CoS session token minted on VM-Xa -> paste once into the Desktop connection",
        f"  S5   Hindsight write/read tokens minted -> cos.env / deploy-v2/m4/.env",
        f"  exec App key {g['app_key_path']} -> execution VM /opt/ea/secrets/app-key.pem (tmpfs 0600)",
        f"  demo repo {g['repos']['demo']} must have the GitHub App installed",
    ]
    return lines


def main() -> int:
    if len(sys.argv) != 3 or sys.argv[2] not in ("--check", "--render"):
        print(__doc__)
        return 1
    inputs_path = pathlib.Path(sys.argv[1])
    if not inputs_path.exists():
        print(f"FAIL: {inputs_path} not found — copy inputs.yaml.example first")
        return 1
    doc, _ = load(inputs_path)
    errs = validate(doc) + check_files(doc)
    if errs:
        print(f"FAIL: {len(errs)} problem(s) in {inputs_path}:")
        for e in errs:
            print(f"  - {e}")
        return 1
    print(f"OK: {inputs_path} valid; all referenced files exist; no embedded secrets")
    for line in staging_plan(doc):
        print(line)
    if sys.argv[2] == "--render":
        hosts = HERE / "m0" / "hosts.env"
        hosts.parent.mkdir(parents=True, exist_ok=True)
        hosts.write_text(render_hosts_env(doc))
        hosts.chmod(0o600)
        print(f"WROTE {hosts} (0600) — re-run the m0 --check-only gate to confirm the scripts see it")
    return 0


if __name__ == "__main__":
    sys.exit(main())
